"""Check subgroup graphs exactly and enclose the odd-cycle constant."""
from collections import Counter
from math import isqrt
import json

from flint import arb, ctx


def prime(p):
    return p >= 2 and all(p % d for d in range(2, isqrt(p) + 1))


def generator(p):
    n = p - 1
    factors = [d for d in range(2, n + 1) if n % d == 0 and prime(d)]
    return next(g for g in range(2, p) if all(pow(g, n // d, p) != 1 for d in factors))


def odd_girth(b, steps):
    if not steps:
        return 0
    mask = (1 << b) - 1
    bits = sum(1 << i for i in steps)

    def shifted(a, k):
        return ((a << k) | (a >> (b - k))) & mask

    if any(shifted(bits, k) & bits for k in steps):
        return 3
    # Even-length reachability grows monotonically because an edge can retrace.
    current = 1
    for length in range(1, 2 * b + 2, 2):
        nxt = 0
        for k in steps:
            nxt |= shifted(current, k)
        if nxt & 1:
            return length
        even = 0
        for k in steps:
            even |= shifted(nxt, k)
        if even == current:
            return 0
        current = even
    raise AssertionError("parity reachability did not stabilize")


def emit(**row):
    print(json.dumps(row, sort_keys=True))


def scan(limit):
    counts = Counter()
    classes = Counter()
    for p in range(5, limit + 1, 4):
        if not prime(p):
            continue
        n = (p - 1) // 2
        g = generator(p)
        counts["primes"] += 1
        for b in range(1, n + 1):
            if n % b:
                continue
            root = pow(g, (p - 1) // b, p)
            mask = [pow((1 - pow(root, j, p)) % p, n, p) for j in range(b)]
            for sigma in [-1, 1]:
                steps = {j for j, m in enumerate(mask) if m == (-sigma) % p}
                assert all((-j % b) in steps for j in steps)
                k = len(steps)
                assert (b - 1 - 2 * k) ** 2 <= p
                girth = odd_girth(b, steps)
                counts["signed_subgroups"] += 1
                classes[girth] += 1
                if girth >= 5:
                    assert girth * k <= 2 * b
                # An independent set of size ceil(b/2) would fit in the prime clique.
                h = (b + 1) // 2 + (sigma == 1)
                if h * (h - 1) > n:
                    assert girth
                if b % 2 == 0 and sigma == 1:
                    square_forbidden = any((2 * j) % b in steps for j in range(b))
                    assert square_forbidden == (girth == 3)
                    if square_forbidden:
                        assert any(j in steps and 2 * j % b in steps for j in range(b))
                    if b * (b + 2) > 4 * n:
                        assert square_forbidden
                        counts["forced_plus_triangles"] += 1
                if p >= 757 and b * b >= 4 * n and h * (h - 1) > n:
                    assert 3 <= girth <= 13
                    counts["uniform_cycle_bound"] += 1
    emit(kind="integer_prime_sweep", limit=limit, counts=dict(counts),
         odd_girth_or_zero_if_bipartite=dict(sorted(classes.items())))


ctx.prec = 192
scan(5000)
c = (arb(1) / 13).cos_pi()
rho = c / (1 + c)
assert arb(4926) / 10000 < rho < arb(4927) / 10000
emit(kind="odd_cycle_constant", denominator=13, mass_lower="0.4926", mass_upper="0.4927",
     finite_cutoff=757)
# Order-five C5 in the plus case at p=41, generated by a forbidden step.
p = 41
root = 16
assert pow(root, 5, p) == 1
assert [j for j in range(5) if pow((1 - pow(root, j, p)) % p, 20, p) == 40] == [1, 4]
c = (arb(1) / 5).cos_pi()
m = 1 / arb(5).sqrt()
assert abs(c / (1 + c) - m) < arb(1) / 10**50
# Quotient law with mass m at zero and equal remaining mass at indices +/-2.
assert abs(m + (1 - m) * (arb(4) / 5).cos_pi()) < arb(1) / 10**50
emit(kind="sharp_unmarked_quotient", p=p, subgroup_order=5, generator=root,
     forbidden_powers=[1, 4], mass="1/sqrt(5)", nonzero_quotient_indices=[0, 2, 3])
