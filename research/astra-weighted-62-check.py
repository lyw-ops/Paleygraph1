"""Net donor-to-recipient radii over the complete p=97 even face and interval tests."""

import contextlib
import importlib.util
import io
import json
from math import gcd
from pathlib import Path

spec = importlib.util.spec_from_file_location(
    "charged61", Path(__file__).with_name("astra-charged-61-check.py"))
charged = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(charged)
n = charged.n
face = charged.face


def record(**data):
    print(json.dumps(data, sort_keys=True))


# A line of the central sign arrangement is generated by (-c,b).
lines = []
for _, b, c in charged.rows:
    if not (b or c):
        continue
    if all((b * v - c * u) % charged.mod for u, v in lines):
        lines.append((b, c))
assert len(lines) >= 2
differences = []
for u, v in lines:
    h = [(-b * v + c * u) % charged.mod for _, b, c in charged.rows]
    assert h[0] == face.zero and sum(h) % charged.mod == face.zero
    donor = [-value if charged.sign(value) < 0 else face.zero for value in h]
    recipient = [value if charged.sign(value) > 0 else face.zero for value in h]
    assert any(donor) and any(recipient)
    differences.append((donor, recipient))

radii = {}
for gen in range(1, n):
    if gcd(gen, n) == 1:
        radii[gen] = max(charged.radius(charged.intervals(d, gen),
                                        charged.intervals(r, gen))
                         for d, r in differences)
record(kind="all_even_face_net_only_nonwrapping_radii", p=97, n=n,
       sign_arrangement_lines=len(lines), radii=radii, minimum=min(radii.values()),
       replayed_bulk_rerouting_minimum=charged.best)

# An exact finite input to the interval theorem. The field primitive roots
# below are verified by their actual generated multiplicative orders.
for p, b, max_r in [(97, 5, 4), (1009, 11, 5), (9413, 3, 6)]:
    n = (p - 1) // 2
    b = b * b % p
    group = [pow(b, k, p) for k in range(n)]
    if len(set(group)) != n:
        b = next(g for g in range(2, p) if pow(g, n, p) == 1 and
                 len({pow(g, k, p) for k in range(n)}) == n)
        group = [pow(b, k, p) for k in range(n)]
    signs = [pow((1 - u) % p, n, p) for u in group]
    counts = {}
    for s, forbidden in [(1, p - 1), (-1, 1)]:
        zeros = {0} | {i for i in range(n) if signs[i] == forbidden}
        starts = set(zeros)
        counts[s] = []
        for r in range(1, max_r + 1):
            starts.intersection_update((j - r + 1) % n for j in zeros)
            counts[s].append(len(starts))
            # N >= n/2^r - r*sqrt(p)/2 - r/2 (each zero factor contributes <=1/2).
            positive_deficit = max(0, 2*n - (2**r)*(2*len(starts)+r))
            assert positive_deficit**2 <= (2**r * r)**2*p
    record(kind="mass_zero_forbidden_run_counts", p=p, n=n,
           primitive_square=b, r_values=list(range(1, max_r + 1)), counts=counts)
